    kg=G*1.15/1000; parcels=max(1,math.ceil(kg/5.0)); fr=FREIGHT*parcels if free else 0
    return dict(R=R,W=W,C=C,kg=round(kg,2),parcels=parcels,fr=fr,n=sum(qty.values()),ns=len(qty),
        save=R-P,gm=(P-C)/P,netm=(P-C-fr)/P,disc=1-P/R,
        comp_disc=1-P/(R+fr) if free else 1-P/R,
        agent=round(P*0.8/10)*10, avg=P/sum(qty.values()))
